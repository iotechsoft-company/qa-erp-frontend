#!/usr/bin/env node
// PreToolUse guard — blocks actions that have bitten this repo (shared working tree with another agent,
// secrets, read-only ERP source). Fast (<100ms), no network. Bypass for a human: run the command yourself.
import path from 'node:path'

import { deny, describeToolCall, readDotEnv, readInput, readonlyDirs, repoRoot } from './lib.mjs'

const EVENT = 'PreToolUse'
const input = readInput()
const root = repoRoot(input.cwd)
const call = describeToolCall(input, root)

const SHARED_TREE = 'Another agent (Claude Code / Codex) may have uncommitted work in this working tree.'

// ─── Bash ────────────────────────────────────────────────────
if (call.kind === 'bash') {
  // Drop heredoc bodies (docs, scripts, commit messages written via <<EOF) so text *about* a command
  // isn't mistaken for running it.
  const cmd = call.command.replace(/<<-?\s*(['"]?)(\w+)\1[^\n]*\n[\s\S]*?\n\s*\2(?=\s|$)/g, '<<heredoc')
  const rules = [
    [
      /\bgit\s+add\s+(-A\b|--all\b|\.(\s|$)|:\/)/,
      `"git add -A/./--all" stages everything. ${SHARED_TREE} Stage explicit paths: git add <file> <file>.`,
    ],
    [
      /\bgit\s+commit\b[^|;&]*\s-[a-zA-Z]*a/,
      `"git commit -a" commits every modified file. ${SHARED_TREE} Stage explicit paths, then git commit.`,
    ],
    [
      /\bgit\s+push\b[^|;&]*(\s--force\b|\s-f\b|\s--force-with-lease\b|\s\+\S)/,
      'Force-push is blocked for agents. Ask the user to do it manually if really needed.',
    ],
    [/\bgit\s+reset\s+[^|;&]*--hard\b/, `"git reset --hard" discards uncommitted changes. ${SHARED_TREE}`],
    [/\bgit\s+clean\s+[^|;&]*-[a-zA-Z]*f/, `"git clean -f" deletes untracked files. ${SHARED_TREE}`],
    [
      /\bgit\s+(checkout|restore)\s+(--\s+)?\.(\s|$)/,
      `Restoring the whole tree discards uncommitted changes. ${SHARED_TREE} Restore specific files only.`,
    ],
    [/\bgit\s+stash\b(?!\s+(list|show))/, `"git stash" hides the other agent's uncommitted work. ${SHARED_TREE}`],
    [
      /(>>?|\btee\b[^|;&]*)\s*\.env(\s|$)|\bsed\s+-i[^|;&]*\s\.env(\s|$)/,
      '.env holds credentials — edit it only via scripts/provision-test-users.ts or ask the user.',
    ],
  ]
  for (const [re, reason] of rules) if (re.test(cmd)) deny(EVENT, `Blocked by qa hook: ${reason}`)

  const writeish =
    /\b(rm|mv|cp|tee|touch|mkdir)\b|\bsed\s+-i|\bperl\s+-pi|\bgit\s+(-C\s+\S+\s+)?(add|commit|push|reset|checkout|restore|clean|stash|rebase|merge)\b|\bpnpm\s+(add|install|remove)\b/
  for (const dir of readonlyDirs(root)) {
    const redirectInto = cmd
      .split(/>>?/)
      .slice(1)
      .some((after) => after.trimStart().startsWith(dir))
    if (cmd.includes(dir) && (writeish.test(cmd) || redirectInto)) {
      deny(
        EVENT,
        `Blocked by qa hook: ${dir} is the app under test — read it, never modify it. File a bug with the report-bug skill instead.`,
      )
    }
  }
  process.exit(0)
}

// ─── File edits (Claude Edit/Write/MultiEdit, Codex apply_patch) ─────────
if (call.kind === 'edit') {
  for (const file of call.files) {
    const rel = path.relative(root, file)
    if (/^\.env$|^\.env\.(?!example$)/.test(rel)) {
      deny(
        EVENT,
        'Blocked by qa hook: .env holds credentials — do not edit it from an agent (provision script / user only).',
      )
    }
    if (rel.startsWith('.auth/'))
      deny(EVENT, 'Blocked by qa hook: .auth/ is generated by `pnpm auth` and holds session tokens.')
    for (const dir of readonlyDirs(root)) {
      if (file === dir || file.startsWith(dir + path.sep)) {
        deny(
          EVENT,
          `Blocked by qa hook: ${dir} is the app under test — never modify it. File a bug with the report-bug skill instead.`,
        )
      }
    }
  }

  // Content scan only for files inside this repo (they get committed).
  const inRepo = call.files.some((f) => !path.relative(root, f).startsWith('..'))
  if (inRepo && call.added) {
    const env = readDotEnv(root)
    const secrets = Object.entries(env)
      .filter(([k, v]) => /PASSWORD|TOKEN|SECRET/.test(k) && v.length >= 6)
      .map(([k, v]) => [k, v])
    for (const [k, v] of secrets) {
      if (call.added.includes(v))
        deny(
          EVENT,
          `Blocked by qa hook: the edit contains the value of ${k} from .env. Read it via src/config/env.ts instead.`,
        )
    }
    // Hosts that must never be committed (e.g. the backend API domain) — configured locally in .env.
    for (const host of (env.QA_FORBIDDEN_STRINGS ?? '')
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)) {
      if (call.added.includes(host))
        deny(
          EVENT,
          'Blocked by qa hook: the edit contains a forbidden string from QA_FORBIDDEN_STRINGS (e.g. the API domain). Call the API through BASE_URL/api/* instead.',
        )
    }
    if (/\beyJ[A-Za-z0-9_-]{15,}\.[A-Za-z0-9_-]{15,}\./.test(call.added)) {
      deny(EVENT, 'Blocked by qa hook: the edit contains what looks like a JWT. Never commit tokens.')
    }
  }
}
process.exit(0)
